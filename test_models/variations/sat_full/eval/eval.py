"""Satellite silage candidates (share change, stress) against their bases on the 15 sample states, 2017-2024.

The pre-registration is README.md section 1, hashed into out/preregistration.sha256 before any score; every step
checks the hash and stops if the section changed. This module implements exactly that text.

Bases are read from the monthly harness (A-S3, report reversion, persistence) and the silage_combos backtest (SC,
SC_A, SC_B at Sep/Oct/Nov). Missing dates (SC family at Jul/Aug/Dec) and 2025 (information only) are regenerated by
importing the owners' code unchanged, with the monthly harness's in-memory widening of the as-of map. Gates check
that regenerated values reproduce the stored ones. No file outside this folder is written; bytecode writing is off.

Steps (each reuses its cache unless --force):
    bases   regenerate + gate + assemble the base table      -> out/cache/bases.parquet, out/gates.json
    score   candidates, metrics, decision, CIs, robustness,
            grids, 2026                                      -> out/*.csv, out/run.json
    all     both

Run from the repository root:
    .venv/Scripts/python.exe -B test_models/variations/sat_full/eval/eval.py all --workers 6
"""

