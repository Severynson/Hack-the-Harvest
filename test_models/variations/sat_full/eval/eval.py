def forecast_2026(preds_all: pd.DataFrame, bases: pd.DataFrame, models: list[str], by_year_preds: pd.DataFrame,
                  with_intervals: bool) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Point values (and, for adopted models, 80% intervals) for 2026 at Sep/Oct/Nov."""
    corn = pd.read_csv(CORN_METRICS, dtype={"state_fips": str})
    corn = corn[(corn["regime"] == "P") & (corn["pool"] == "all") & (corn["year"] == INFO_YEAR)
                & (corn["state_fips"] != "ALL")]
    st = pd.read_csv(STRESS)
    st = st[(st["weight"] == "none") & (st["scale"] == "rms") & (st["year"] == INFO_YEAR)]
    delta = st.pivot(index="state", columns="mask", values="stress")
    delta = (delta["P"] - delta["CDL"]).reindex(STATES15)
    rows, us_rows = [], []
    for model in models:
        base = base_of(model)
        for asof in COMBO_DATES:
            p = preds_all[(preds_all["model"] == model) & (preds_all["asof"] == asof)
                          & (preds_all["year"] == FORECAST_YEAR)].set_index("state")
            b = bases[(bases["base"] == base) & (bases["asof"] == asof)
                      & (bases["year"] == FORECAST_YEAR)].set_index("state")["pred"]
            if p.empty:
                continue
            row = {"model": model, "display": display(model), "asof": asof}
            w_s = pd.Series(0.0, index=STATES15)
            q = None
            if with_intervals and model in CANDIDATES:
                hist = by_year_preds[(by_year_preds["model"] == model) & (by_year_preds["asof"] == asof)
                                     & by_year_preds["year"].isin(SCORE_YEARS)
                                     & by_year_preds["state"].isin(STATES15)]
                e = np.log(hist["actual"] / hist["pred"])
                q = np.percentile(e, [10, 50, 90])
                c = CANDIDATES[model]
                if c["kind"] == "sat":
                    m = np.log(corn[corn["asof"] == asof].set_index("state")["corn_acre_ratio"].reindex(STATES15))
                    big = float(np.sqrt(np.mean(m ** 2)))
                    w_s = Z80 * EXPONENT * np.maximum(m.abs(), big)
                else:
                    big = float(np.sqrt(np.mean(delta ** 2)))
                    w_s = Z80 * STRESS_B * np.maximum(delta.abs(), big)
            for s in STATES15:
                rec = {**row, "state": s, "base_pred": float(b.get(s, np.nan)), "pred": float(p.loc[s, "pred"]),
                       "satellite_available": bool(p.loc[s, "available"] == 1), "factor": float(p.loc[s, "factor"])}
                if q is not None:
                    c_s = rec["pred"]
                    rec["lo80"] = c_s * np.exp(q[1] - np.sqrt((q[1] - q[0]) ** 2 + w_s[s] ** 2))
                    rec["hi80"] = c_s * np.exp(q[1] + np.sqrt((q[2] - q[1]) ** 2 + w_s[s] ** 2))
                    rec["mask_widening_log"] = float(w_s[s])
                rows.append(rec)
            total15 = float(p.loc[STATES15, "pred"].sum())
            total48 = float(p["pred"].sum())
            us = {**row, "states_in_us_total": int(len(p)), "total15": total15, "base_total15":
                  float(b.reindex(STATES15).sum()), "us48": total48, "base_us48": float(b.sum())}
            if q is not None:
                hy = by_year_preds[(by_year_preds["model"] == model) & (by_year_preds["asof"] == asof)
                                   & by_year_preds["year"].isin(SCORE_YEARS)]
                tot = hy.groupby("year")[["actual", "pred"]].sum()
                u = np.percentile(np.log(tot["actual"] / tot["pred"]), [10, 50, 90])
                big_w = float(np.sqrt(sum((p.loc[s, "pred"] * w_s[s]) ** 2 for s in STATES15)) / total48)
                us["us48_lo80"] = total48 * np.exp(u[1] - np.sqrt((u[1] - u[0]) ** 2 + big_w ** 2))
                us["us48_hi80"] = total48 * np.exp(u[1] + np.sqrt((u[2] - u[1]) ** 2 + big_w ** 2))
                us["us_mask_widening_log"] = big_w
            us_rows.append(us)
    return pd.DataFrame(rows), pd.DataFrame(us_rows)


def loyo_coverage(by_year_preds: pd.DataFrame, model: str, asof: str) -> float:
    h = by_year_preds[(by_year_preds["model"] == model) & (by_year_preds["asof"] == asof)
                      & by_year_preds["year"].isin(SCORE_YEARS) & by_year_preds["state"].isin(STATES15)].copy()
    h["e"] = np.log(h["actual"] / h["pred"])
    hits = []
    for y in SCORE_YEARS:
        q10, q90 = np.percentile(h.loc[h["year"] != y, "e"], [10, 90])
        t = h[h["year"] == y]
        hits.extend(((t["e"] >= q10) & (t["e"] <= q90)).tolist())
    return float(np.mean(hits))


