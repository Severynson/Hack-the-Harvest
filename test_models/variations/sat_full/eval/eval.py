def tier_a_columns(summary: pd.DataFrame, mask: str) -> tuple[list[str], str]:
    nov = summary[(summary["asof"] == PRIMARY)].set_index("model")["WAPE15"]
    k0, k1 = f"SCA_sat_K0_{mask}", f"SCA_sat_K1_{mask}"
    best = k0 if nov[k0] < nov[k1] else k1
    cols = ["AS3", f"AS3_sat_K0_{mask}", f"AS3_sat_K1_{mask}", f"AS3_stress_{mask}", "SCA", best,
            f"SCA_stress_{mask}", "REV", "PER"]
    return cols, best


def sc_columns(mask: str) -> list[str]:
    return ["SC", f"SC_sat_K0_{mask}", f"SC_sat_K1_{mask}", f"SC_stress_{mask}", "SCB", "REV", "PER"]


def grid(summary: pd.DataFrame, cols: list[str], second: str, as3_fb: pd.DataFrame, names: dict | None = None
         ) -> tuple[pd.DataFrame, str]:
    rows_order = [LABEL[d] for d in DATES] + list(AVERAGES)
    key_of = {LABEL[d]: d for d in DATES} | {k: k for k in AVERAGES}
    s = summary.set_index(["model", "asof"])
    fb_years = as3_fb[as3_fb["year"].isin(SCORE_YEARS)].groupby("asof")["fallback"].sum()
    header = [names.get(c, display(c)) if names else display(c) for c in cols]
    csv_rows, md_rows = [], []
    for label in rows_order:
        key = key_of[label]
        vals = []
        for c in cols:
            if (c, key) not in s.index:
                vals.append(None)
                continue
            r = s.loc[(c, key)]
            vals.append((round(float(r["WAPE15"]), 2), round(float(r[second]), 2), r))
        ok = [v for v in vals if v is not None]
        best_w = min(v[0] for v in ok) if ok else None
        best_t = min(v[1] for v in ok) if ok else None
        cells, mds = [], []
        for c, v in zip(cols, vals):
            if v is None:
                cells.append("UNCOMPUTED: base missing at this date")
                mds.append("UNCOMPUTED")
                continue
            w, t, r = v
            mark = ""
            if c in CANDIDATES:
                if bool(r["all_fallback"]):
                    mark = " *"
                elif key in MONTHS and int(r["fallback_state_years"]) > 0:
                    mark = f" *{int(r['fallback_state_years'])}"
            if base_of(c) == "AS3" and key in MONTHS:
                k = int(fb_years.get(key, 0))
                mark += " (F)" if k == len(SCORE_YEARS) else (f" ({k}/{len(SCORE_YEARS)} F)" if k else "")
            cells.append(f"{w:.2f} / {t:.2f}{mark}")
            ws = f"**{w:.2f}**" if w == best_w else f"{w:.2f}"
            ts = f"**{t:.2f}**" if t == best_t else f"{t:.2f}"
            mds.append(f"{ws} / {ts}{mark}")
        csv_rows.append([label] + cells)
        md_rows.append(f"| {label} | " + " | ".join(mds) + " |")
    frame = pd.DataFrame(csv_rows, columns=["Date"] + header)
    md = "| Date | " + " | ".join(header) + " |\n|" + "---|" * (len(header) + 1) + "\n" + "\n".join(md_rows)
    return frame, md


