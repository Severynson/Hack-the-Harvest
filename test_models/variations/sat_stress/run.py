"""sat_stress: a satellite crop-stress index as a direct silage-chopping signal (agent key: sat_stress).

Implements README.md section 1 (pre-registered, hash in out/preregistration.sha256). Steps:
    1. Per sampled state and year 2019-2024, field-level peak NDVI (Jun 1-Sep 15), mean NDMI (Aug 1-Sep 15)
       and NDVI decline from the peak to Sep 1-15, from looks dated on or before Sep 15; state medians;
       anomalies against prior years only; one composite stress index.
    2. Bases: A-S3 (read from test_models/ownModels/silage/out) and SC (smoothed_chopping, regenerated by
       importing kernelag.silage_level; kernelag is never modified).
    3. Candidates c1, c2 (fitted b, expanding window), c3a, c3b (b fixed at 0.05), scored on the 15 states.
    4. Decision rule, diagnostics, outputs in out/.

Run from the repo root:
    .venv/Scripts/python.exe test_models/variations/sat_stress/run.py [--workers 8]
"""

