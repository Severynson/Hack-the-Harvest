# ------------------------------------------------------------------------------------------ pre-registration

def preregistration_status() -> dict:
    text = (HERE / "README.md").read_text(encoding="utf-8")
    section = text[text.index(PREREG_START):text.index(PREREG_END) + len(PREREG_END)]
    now = hashlib.sha256(section.encode("utf-8")).hexdigest()
    stored = (OUT / "preregistration.sha256").read_text(encoding="utf-8").split()[0]
    return {"sha256_now": now, "sha256_stored": stored, "unchanged": now == stored}


# ------------------------------------------------------------------------------------------ stress index

def _md(dates: pd.Series) -> np.ndarray:
    return (dates.dt.month * 100 + dates.dt.day).to_numpy()


def field_components(g: pd.DataFrame) -> dict:
    """The three components of one field-year from its clear looks (already cut at 15 September)."""
    g = g.sort_values("date").reset_index(drop=True)
    g = drop_dips(g.assign(doy=g["date"].dt.day_of_year.astype(int)))
    md = _md(g["date"])
    out = {"peak": np.nan, "ndmi": np.nan, "decline": np.nan, "n_looks": len(g)}
    in_peak = (md >= PEAK_WINDOW[0]) & (md <= PEAK_WINDOW[1])
    if in_peak.sum() >= MIN_PEAK_LOOKS:
        out["peak"] = float(g.loc[in_peak, "ndvi"].max())
    in_ndmi = (md >= NDMI_WINDOW[0]) & (md <= NDMI_WINDOW[1]) & g["ndmi"].notna().to_numpy()
    if in_ndmi.sum() >= MIN_NDMI_LOOKS:
        out["ndmi"] = float(g.loc[in_ndmi, "ndmi"].mean())
    in_late = (md >= LATE_WINDOW[0]) & (md <= LATE_WINDOW[1])
    if in_late.sum() >= MIN_LATE_LOOKS and np.isfinite(out["peak"]):
        out["decline"] = out["peak"] - float(g.loc[in_late, "ndvi"].median())
    return out


def state_fields(fips: str) -> pd.DataFrame:
    """Field-year components for one sampled state, 2019-2024, complete areas only."""
    data = data_dir()
    sample = pd.read_parquet(data / "samples" / f"corn_{fips}.parquet",
                             columns=["field_id", "cell", "year", "acres"])
    sample["field_id"] = sample["field_id"].astype(str)
    sample = sample[sample["year"].isin(SAT_YEARS)]
    folder = data / "s2_series" / f"corn_{fips}"
    cells = set(complete_areas(sample, folder))
    sample = sample[sample["cell"].isin(cells)]
    parts = []
    for (cell, year), _ in sample.groupby(["cell", "year"]):
        path = folder / f"{cell}_{year}.csv"
        parts.append(pd.read_csv(path, dtype={"field_id": str}, parse_dates=["date"]))
    series = pd.concat(parts, ignore_index=True).drop_duplicates(["field_id", "year", "date"])
    series = series[(series["valid_frac"] >= MIN_VALID) & series["ndvi"].notna()]
    series = series[_md(series["date"]) <= CUT_MD]
    series = series.merge(sample[["field_id", "year"]].drop_duplicates(), on=["field_id", "year"], how="inner")
    rows = [{"field_id": fid, "year": int(year), **field_components(g)}
            for (fid, year), g in series.groupby(["field_id", "year"], sort=False)]
    fields = pd.DataFrame(rows)
    fields = sample[["field_id", "year", "cell"]].merge(fields, on=["field_id", "year"], how="left")
    fields.insert(0, "state_fips", fips)
    return fields


def stress_table(fields: pd.DataFrame) -> pd.DataFrame:
    """State-year medians, prior-years anomalies, z-scores and the composite stress index."""
    rows = []
    for (fips, year), g in fields.groupby(["state_fips", "year"]):
        row = {"state_fips": fips, "state": STATES[fips], "year": int(year), "fields_sampled": len(g)}
        for comp in COMPONENTS:
            vals = g[comp].dropna()
            row[f"n_{comp}"] = len(vals)
            row[comp] = float(vals.median()) if len(vals) >= MIN_FIELDS else np.nan
        rows.append(row)
    table = pd.DataFrame(rows).sort_values(["state_fips", "year"]).reset_index(drop=True)
    for comp in COMPONENTS:
        prior = table.groupby("state_fips")[comp].transform(lambda s: s.shift(1).expanding(min_periods=1).mean())
        table[f"anom_{comp}"] = table[comp] - prior
        sigma = {}
        for year in SCORE_YEARS:
            a = table.loc[table["year"].between(SCORE_YEARS[0], year), f"anom_{comp}"].dropna()
            sigma[year] = float(np.sqrt((a ** 2).mean())) if len(a) else np.nan
        table[f"sigma_{comp}"] = table["year"].map(sigma)
        table[f"z_{comp}"] = table[f"anom_{comp}"] / table[f"sigma_{comp}"]
    table["stress"] = sum(sign * table[f"z_{comp}"] for comp, sign in COMPONENTS.items()) / len(COMPONENTS)
    return table


# ------------------------------------------------------------------------------------------ bases

def truth_table() -> tuple[pd.DataFrame, dict]:
    """NASS final silage acres: the incumbent's panel (2013 on); Quick Stats finals fill earlier years."""
    panel = load_panel("nov")[["state", "year", "silage"]].rename(columns={"silage": "actual"}).dropna()
    qs = silage_level.load_history(data_dir() / QUICKSTATS_DIR, "nov")["silage"]
    qs = qs.stack().rename("qs").reset_index().rename(columns={"level_0": "year", "level_1": "state"})
    qs.columns = ["year", "state", "qs"]
    both = panel.merge(qs, on=["state", "year"])
    check = {"panel_years": f"{panel['year'].min()}-{panel['year'].max()}", "overlap_rows": len(both),
             "overlap_max_abs_diff": float((both["actual"] - both["qs"]).abs().max())}
    early = qs[qs["year"] < panel["year"].min()].rename(columns={"qs": "actual"})
    return pd.concat([early[["state", "year", "actual"]], panel], ignore_index=True), check


def as3_base() -> pd.DataFrame:
    raw = pd.read_csv(AS3_FILE)
    raw = raw[raw["candidate"] == AS3_CANDIDATE].drop(columns=["asof"])
    return raw.rename(columns={"asof_key": "asof"})[["state", "year", "asof", "pred", "actual", "last"]]


def _shortfall(history: dict) -> pd.DataFrame:
    """SC's yield shortfall (1 - in-season yield / 10-year trend), the same formula as chopping_exposure."""
    final = history["yield"]
    years = sorted(set(final.index) | set(history["yield_asof"].index))
    trend = pd.DataFrame(np.nan, index=years, columns=final.columns)
    for year in years:
        past = final.loc[year - silage_level.TREND_YEARS:year - 1]
        for state in final.columns:
            y = past[state].dropna()
            if len(y) >= silage_level.MIN_TREND_YEARS:
                trend.loc[year, state] = np.polyval(np.polyfit(y.index, y.to_numpy(), 1), year)
    return 1 - history["yield_asof"].reindex(index=years, columns=final.columns) / trend


def sc_base() -> tuple[pd.DataFrame, list[dict]]:
    """smoothed_chopping predictions 2012-2024 for every state, at each as-of date, via kernelag."""
    folder = data_dir() / QUICKSTATS_DIR
    parts, params = [], []
    for asof in ASOFS:
        history = silage_level.load_history(folder, asof)
        exposure = silage_level.chopping_exposure(history)
        shortfall = _shortfall(history)
        for year in BASE_YEARS:
            pred, p = silage_level.predict(history, year, exposure)
            params.append({"asof": asof, "year": year, **p})
            chopped = p["gamma"] * exposure.loc[year].reindex(pred.index).fillna(0.0)
            parts.append(pd.DataFrame({
                "state": pred.index, "year": year, "asof": asof, "pred": pred.to_numpy(),
                "chopped_acres": chopped.to_numpy(),
                "shortfall": shortfall.loc[year].reindex(pred.index).to_numpy() if year in shortfall.index
                else np.nan}))
    return pd.concat(parts, ignore_index=True), params


def errors(pred: pd.Series, actual: pd.Series) -> dict:
    miss = pred - actual
    return {"wape_pct": 100 * miss.abs().sum() / actual.sum(), "total_err_pct": 100 * miss.sum() / actual.sum(),
            "n_states": int(len(actual))}


def sc_reproduction(sc: pd.DataFrame, truth: pd.DataFrame, states48: list[str]) -> dict:
    """Regenerated SC against the stored incumbent backtest (per year) and the documented means."""
    out = {}
    for asof, path in INCUMBENT_BACKTEST.items():
        stored = pd.read_csv(path)
        stored = stored[(stored["scope"] == "all_states") & (stored["series"] == "silage")
                        & (stored["predictor"] == "smoothed_chopping")].set_index("year")
        rows = []
        for year in stored.index:
            p = sc[(sc["asof"] == asof) & (sc["year"] == year)].merge(truth, on=["state", "year"])
            p = p[p["state"].isin(states48)]
            e = errors(p["pred"], p["actual"])
            rows.append({"year": int(year), "regenerated_wape": round(e["wape_pct"], 2),
                         "stored_wape": float(stored.loc[year, "state_error_pct"]),
                         "regenerated_total": round(e["total_err_pct"], 2),
                         "stored_total": float(stored.loc[year, "total_error_pct"]),
                         "n_regenerated": e["n_states"], "n_stored": int(stored.loc[year, "n_states"])})
        frame = pd.DataFrame(rows)
        out[f"per_year_{asof}"] = rows
        out[f"max_abs_wape_diff_{asof}"] = float((frame["regenerated_wape"] - frame["stored_wape"]).abs().max())
        out[f"max_abs_total_diff_{asof}"] = float((frame["regenerated_total"] - frame["stored_total"]).abs().max())
    means = {}
    for label, years in {"2012-2024": BASE_YEARS, "2017-2024": list(range(2017, 2025))}.items():
        per = []
        for year in years:
            p = sc[(sc["asof"] == "nov") & (sc["year"] == year)].merge(truth, on=["state", "year"])
            p = p[p["state"].isin(states48)]
            per.append(errors(p["pred"], p["actual"]))
        means[label] = {"state_wape": round(float(np.mean([e["wape_pct"] for e in per])), 2),
                        "us_abs": round(float(np.mean([abs(e["total_err_pct"]) for e in per])), 2),
                        "documented": DOCUMENTED_SC[label]}
    out["means_nov_48_states"] = means
    return out


# ------------------------------------------------------------------------------------------ candidates

def fit_b(train: pd.DataFrame) -> float:
    """max(0, WLS slope without intercept of log(actual / base) on stress, weights = base acres)."""
    t = train.dropna(subset=["stress"])
    if t.empty:
        return 0.0
    y, x, w = np.log(t["actual"] / t["base"]), t["stress"], t["base"]
    denom = float((w * x * x).sum())
    return max(0.0, float((w * x * y).sum()) / denom) if denom > 0 else 0.0


def candidates(rows: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    """rows: state, year, asof, base_name, base, actual, stress (15 states). Adds candidate predictions."""
    preds, fitted = [], []
    for (base_name, asof), g in rows.groupby(["base_name", "asof"]):
        tag = {"AS3": ("c1_as3_fit", "c3a_as3_fixed"), "SC": ("c2_sc_fit", "c3b_sc_fixed")}[base_name]
        for year in SCORE_YEARS:
            cur = g[g["year"] == year].copy()
            b = fit_b(g[g["year"].between(SCORE_YEARS[0], year - 1)])
            n_train = int(g[g["year"].between(SCORE_YEARS[0], year - 1)]["stress"].notna().sum())
            fitted.append({"candidate": tag[0], "asof": asof, "year": year, "b": b, "n_train": n_train})
            s = cur["stress"].fillna(0.0)
            for name, coef in [(tag[0], b), (tag[1], B_FIXED)]:
                preds.append(cur.assign(candidate=name, pred=cur["base"] * np.exp(coef * s)))
            preds.append(cur.assign(candidate=f"base_{base_name}", pred=cur["base"]))
            preds.append(cur.assign(candidate="ref_persistence", pred=cur["last"]))
    out = pd.concat(preds, ignore_index=True).drop_duplicates(["candidate", "asof", "state", "year"])
    return out, pd.DataFrame(fitted)


BASE_OF = {"c1_as3_fit": "base_AS3", "c3a_as3_fixed": "base_AS3", "c2_sc_fit": "base_SC", "c3b_sc_fixed": "base_SC"}
WINDOW = {"c1_as3_fit": list(range(2021, 2025)), "c2_sc_fit": list(range(2021, 2025)),
          "c3a_as3_fixed": SCORE_YEARS, "c3b_sc_fixed": SCORE_YEARS}


def by_year(preds: pd.DataFrame, others48: pd.DataFrame) -> pd.DataFrame:
    """15-state metrics, plus 48-state metrics where the 33 other states keep the base."""
    rows = []
    for (cand, asof, year), g in preds.groupby(["candidate", "asof", "year"]):
        e15 = errors(g["pred"], g["actual"])
        row = {"candidate": cand, "asof": asof, "year": int(year), "wape15_pct": e15["wape_pct"],
               "total15_err_pct": e15["total_err_pct"], "abs_total15_err_pct": abs(e15["total_err_pct"]),
               "n15": e15["n_states"]}
        base = BASE_OF.get(cand, cand if cand.startswith("base_") else None)
        if base is not None:
            rest = others48[(others48["base_name"] == base.split("_")[1]) & (others48["asof"] == asof)
                            & (others48["year"] == year)]
            e48 = errors(pd.concat([g["pred"], rest["base"]]), pd.concat([g["actual"], rest["actual"]]))
            row.update(wape48_pct=e48["wape_pct"], us_err_pct=e48["total_err_pct"],
                       abs_us_err_pct=abs(e48["total_err_pct"]), n48=e48["n_states"])
        rows.append(row)
    return pd.DataFrame(rows)


def paired(table: pd.DataFrame, cand: str, base: str, asof: str, metric: str, years: list[int]) -> dict:
    a = table[(table["candidate"] == cand) & (table["asof"] == asof)].set_index("year")[metric]
    b = table[(table["candidate"] == base) & (table["asof"] == asof)].set_index("year")[metric]
    d = (a - b).reindex(years).dropna()
    se = float(d.std(ddof=1) / np.sqrt(len(d))) if len(d) > 1 else np.nan
    return {"candidate": cand, "base": base, "asof": asof, "metric": metric, "years": f"{years[0]}-{years[-1]}",
            "n": int(len(d)), "cand_mean": float(a.reindex(years).mean()), "base_mean": float(b.reindex(years).mean()),
            "mean_diff": float(d.mean()), "se": se, "diff_plus_2se": float(d.mean() + 2 * se),
            "improves": bool(d.mean() + 2 * se < 0), "years_better": int((d < 0).sum())}


def correlations(frame: pd.DataFrame, xs: list[str], ys: list[str]) -> pd.DataFrame:
    rows = []
    for x in xs:
        for y in ys:
            ok = frame[[x, y]].replace([np.inf, -np.inf], np.nan).dropna()
            if len(ok) < 5:
                rows.append({"x": x, "y": y, "n": len(ok), "pearson": np.nan, "pearson_p": np.nan,
                             "spearman": np.nan, "spearman_p": np.nan})
                continue
            pr, pp = stats.pearsonr(ok[x], ok[y])
            sr, sp = stats.spearmanr(ok[x], ok[y])
            rows.append({"x": x, "y": y, "n": len(ok), "pearson": pr, "pearson_p": pp, "spearman": sr,
                         "spearman_p": sp})
    return pd.DataFrame(rows)


def drought_change() -> pd.DataFrame:
    """Drought Monitor D2+ Jun-Sep mean minus the state's mean over prior years (from 2000), as of nov."""
    from kernelag.context import drought

    usdm = pd.read_csv(next((data_dir() / "drought").glob("usdm_state_weekly_2000_2026.csv*")))
    d = drought(usdm, "nov").sort_values(["state", "year"])
    d = d[d["year"] <= SCORE_YEARS[-1]]
    prior = d.groupby("state")["drought"].transform(lambda s: s.shift(1).expanding(min_periods=1).mean())
    return d.assign(d_drought=d["drought"] - prior)[["state", "year", "d_drought"]]


# ------------------------------------------------------------------------------------------ main

def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--workers", type=int, default=8)
    parser.add_argument("--force", action="store_true", help="recompute field components")
    args = parser.parse_args()
    prereg = preregistration_status()
    if not prereg["unchanged"]:
        raise SystemExit(f"pre-registration section changed since hashing: {prereg}")

    cache = OUT / "field_components.parquet"
    if cache.exists() and not args.force:
        fields = pd.read_parquet(cache)
    else:
        with ProcessPoolExecutor(args.workers) as pool:
            fields = pd.concat(pool.map(state_fields, list(STATES)), ignore_index=True)
        fields.to_parquet(cache, index=False)
    stress = stress_table(fields)
    stress.to_csv(OUT / "stress_by_state_year.csv", index=False, float_format="%.5f")

    truth, truth_source_check = truth_table()
    as3 = as3_base()
    states48 = sorted(as3["state"].unique())
    sc, sc_params = sc_base()
    sc.merge(truth, on=["state", "year"], how="left").to_csv(OUT / "sc_backtest_by_state_year.csv", index=False,
                                                           float_format="%.3f")
    repro = sc_reproduction(sc, truth, states48)
    repro["params_by_asof_year"] = sc_params

    # truth checks: A-S3's actual and SC's history equal the incumbent's truth for the 15 states
    chk = as3[as3["state"].isin(STATES.values())].merge(
        truth, on=["state", "year"], suffixes=("_as3", "_panel"))
    truth_check = {**truth_source_check, "as3_rows": len(chk),
                   "as3_max_abs_diff": float((chk["actual_as3"] - chk["actual_panel"]).abs().max())}

    last = truth.assign(year=truth["year"] + 1).rename(columns={"actual": "last"})
    sc_rows = sc.merge(truth, on=["state", "year"]).merge(last, on=["state", "year"], how="left")
    bases = pd.concat([
        as3.drop(columns=["actual", "last"]).merge(truth, on=["state", "year"]).merge(
            last, on=["state", "year"], how="left").assign(base_name="AS3"),
        sc_rows[["state", "year", "asof", "pred", "actual", "last"]].assign(base_name="SC")],
        ignore_index=True).rename(columns={"pred": "base"})
    bases = bases[bases["state"].isin(states48) & bases["year"].isin(SCORE_YEARS)]
    in15 = bases["state"].isin(STATES.values())
    rows15 = bases[in15].merge(stress[["state", "year", "stress"]], on=["state", "year"], how="left")
    others48 = bases[~in15]
    missing_stress = rows15[rows15["stress"].isna()][["state", "year"]].drop_duplicates()

    preds, fitted = candidates(rows15)
    preds.to_csv(OUT / "predictions_by_state_year.csv", index=False, float_format="%.2f")
    fitted.to_csv(OUT / "fitted_b.csv", index=False, float_format="%.5f")
    table = by_year(preds, others48)
    table.to_csv(OUT / "by_year.csv", index=False, float_format="%.4f")

    decisions = [paired(table, c, BASE_OF[c], asof, m, WINDOW[c])
                 for c in BASE_OF for asof in ASOFS for m in ("wape15_pct", "abs_total15_err_pct")]
    info = [paired(table, c, BASE_OF[c], asof, m, SCORE_YEARS)
            for c in BASE_OF for asof in ASOFS for m in ("wape15_pct", "abs_total15_err_pct", "wape48_pct",
                                                           "abs_us_err_pct")]
    pd.DataFrame(decisions).to_csv(OUT / "decision_tests.csv", index=False, float_format="%.4f")
    pd.DataFrame(info).to_csv(OUT / "paired_2020_2024_all_metrics.csv", index=False, float_format="%.4f")
    summary = table.groupby(["candidate", "asof"])[
        ["wape15_pct", "abs_total15_err_pct", "total15_err_pct", "wape48_pct", "abs_us_err_pct"]].mean()
    summary.reset_index().to_csv(OUT / "summary_2020_2024.csv", index=False, float_format="%.3f")

    # diagnostics
    diag = stress[stress["year"].isin(SCORE_YEARS)][["state", "year", "stress", *[f"z_{c}" for c in COMPONENTS]]]
    for c, sign in COMPONENTS.items():
        diag[f"signed_z_{c}"] = sign * diag[f"z_{c}"]
    scn = sc_rows[sc_rows["asof"] == "nov"].assign(sc_chop_share=lambda d: d["chopped_acres"] / d["pred"])
    diag = diag.merge(scn[["state", "year", "shortfall", "sc_chop_share", "actual", "last", "pred"]],
                      on=["state", "year"], how="left").rename(columns={"pred": "sc_pred"})
